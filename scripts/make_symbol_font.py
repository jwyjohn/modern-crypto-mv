fb = FontBuilder(1200, isTTF=True)
names = ['.notdef'] + [f'u{ord(c):04X}' for c in G]
fb.setupGlyphOrder(names)
fb.setupCharacterMap({ord(c): f'u{ord(c):04X}' for c in G})
glyphs, metrics = {}, {}
pen = TTGlyphPen(None)
glyphs['.notdef'] = pen.glyph()
metrics['.notdef'] = (600, 0)
for c, (top, rows) in G.items():
    pen = TTGlyphPen(None)
    w = max(len(r) for r in rows)
    for j, row in enumerate(rows):
        y = top - j
        for i, ch in enumerate(row):
            if ch == '#':
                x0, y0 = i * 100, y * 100
                pen.moveTo((x0, y0))
                pen.lineTo((x0, y0 + 100))
                pen.lineTo((x0 + 100, y0 + 100))
                pen.lineTo((x0 + 100, y0))
                pen.closePath()
    glyphs[f'u{ord(c):04X}'] = pen.glyph()
    metrics[f'u{ord(c):04X}'] = ((w + 1) * 100, 0)
fb.setupGlyf(glyphs)
fb.setupHorizontalMetrics(metrics)
fb.setupHorizontalHeader(ascent=1300, descent=-300)
fb.setupNameTable({'familyName': 'Crypto Pixel', 'styleName': 'Regular'})
fb.setupOS2(sTypoAscender=1300, sTypoDescender=-300, usWinAscent=1300, usWinDescent=300)
fb.setupPost()
fb.save('public/fonts/CryptoPixel.ttf')
